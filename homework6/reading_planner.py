SQLITE_PATH = Path(__file__).resolve().with_name("reading_planner.sqlite3")
MAX_SQL_INTEGER = 2_147_483_647


def daily_pages(pages, days):
    return (pages + days - 1) // days


class ReadingDatabase:
    def __init__(self, connection, backend):
        self.connection = connection
        self.backend = backend
        self.placeholder = "?" if backend == "SQLite" else "%s"

    @contextmanager
    def transaction(self):
        with closing(self.connection.cursor()) as cursor:
            try:
                yield cursor
                self.connection.commit()
            except Exception:
                self.connection.rollback()
                raise

    def initialize(self):
        primary_key = "INTEGER PRIMARY KEY"
        if self.backend == "PostgreSQL":
            primary_key = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"

        with self.transaction() as cursor:
            if self.backend == "SQLite":
                cursor.execute("PRAGMA foreign_keys = ON")
                cursor.execute("BEGIN")
            cursor.execute(f"""
                CREATE TABLE IF NOT EXISTS books (
                    id {primary_key},
                    title TEXT NOT NULL UNIQUE CHECK (length(trim(title)) > 0)
                )
            """)
            cursor.execute(f"""
                CREATE TABLE IF NOT EXISTS reading_plans (
                    id {primary_key},
                    book_id INTEGER NOT NULL REFERENCES books(id),
                    pages_remaining INTEGER NOT NULL CHECK (pages_remaining > 0),
                    days INTEGER NOT NULL CHECK (days > 0)
                )
            """)
            cursor.execute("""
                CREATE INDEX IF NOT EXISTS reading_plans_book_id_idx
                ON reading_plans (book_id)
            """)

    def read_tables(self):
        with self.transaction() as cursor:
            return self._read_tables(cursor)

    def add_plan(self, title, pages, days):
        value = self.placeholder
        with self.transaction() as cursor:
            cursor.execute(f"""
                INSERT INTO books (title) VALUES ({value})
                ON CONFLICT (title) DO NOTHING
            """, (title,))
            cursor.execute(f"SELECT id FROM books WHERE title = {value}", (title,))
            book_id = cursor.fetchone()[0]
            cursor.execute(f"""
                INSERT INTO reading_plans (book_id, pages_remaining, days)
                VALUES ({value}, {value}, {value})
            """, (book_id, pages, days))
            return self._read_tables(cursor)

    def _read_tables(self, cursor):
        cursor.execute("SELECT id, title FROM books ORDER BY id")
        books = cursor.fetchall()
        cursor.execute("""
            SELECT p.id, p.book_id, b.title, p.pages_remaining, p.days
            FROM reading_plans AS p
            JOIN books AS b ON b.id = p.book_id
            ORDER BY p.id DESC
        """)
        plans = [
            (plan_id, book_id, title, pages, days, daily_pages(pages, days))
            for plan_id, book_id, title, pages, days in cursor.fetchall()
        ]
        return books, plans

    def close(self):
        self.connection.close()


class ReadingPlanner(QMainWindow):
    def __init__(self):
        super().__init__()
        self.setWindowTitle("Читай по плану")
        self.resize(805, 540)
        self.database = None
        local_port = os.environ.pop("READING_PLANNER_PG_PORT", None)
        local_password = os.environ.pop("READING_PLANNER_PG_PASSWORD", None)
        self.local_postgres = (int(local_port), local_password) if local_port and local_password else None

        container = QWidget()
        self.setCentralWidget(container)
        layout = QVBoxLayout(container)
        layout.addWidget(QLabel("Рассчитайте дневную норму чтения"))

        self.title_input = QLineEdit()
        self.title_input.setPlaceholderText("Для сохранения плана")
        self.pages_input = QLineEdit()
        self.pages_input.setPlaceholderText("Например, 250")

        self.deadline = QComboBox()
        self.deadline.setEditable(True)
        self.deadline.setInsertPolicy(QComboBox.InsertPolicy.NoInsert)
        self.deadline.addItems(["7", "14", "30"])

        form = QFormLayout()
        form.addRow("Название книги", self.title_input)
        form.addRow("Осталось страниц", self.pages_input)
        form.addRow("Срок чтения (в днях)", self.deadline)
        layout.addLayout(form)

        actions = QHBoxLayout()
        calculate_button = QPushButton("Рассчитать")
        calculate_button.clicked.connect(self.calculate)
        self.pages_input.returnPressed.connect(self.calculate)
        self.deadline.lineEdit().returnPressed.connect(self.calculate)
        actions.addWidget(calculate_button)
        self.save_button = QPushButton("Сохранить план")
        self.save_button.setEnabled(False)
        self.save_button.clicked.connect(self.save_plan)
        actions.addWidget(self.save_button)
        actions.addStretch()
        layout.addLayout(actions)

        self.result = QLabel()
        self.result.setWordWrap(True)
        layout.addWidget(self.result)

        database_controls = QHBoxLayout()
        database_controls.addWidget(QLabel("СУБД"))
        self.backend = QComboBox()
        self.backend.addItems(["SQLite", "PostgreSQL"])
        self.backend.activated.connect(self.switch_database)
        database_controls.addWidget(self.backend)
        self.refresh_button = QPushButton("Обновить таблицы")
        self.refresh_button.setEnabled(False)
        self.refresh_button.clicked.connect(self.refresh_tables)
        database_controls.addWidget(self.refresh_button)
        database_controls.addStretch()
        layout.addLayout(database_controls)

        self.tabs = QTabWidget()
        self.books_table = self.create_table(["ID книги", "Название"], 1)
        self.plans_table = self.create_table(
            ["ID плана", "ID книги", "Название", "Страниц", "Дней", "Стр. в день"], 2
        )
        self.tabs.addTab(self.plans_table, "Планы чтения")
        self.tabs.addTab(self.books_table, "Книги")
        layout.addWidget(self.tabs)
        self.statusBar().showMessage("База данных не подключена")
        self.switch_database(0)
        self.pages_input.setFocus()

    def create_table(self, headers, stretch_column):
        table = QTableWidget(0, len(headers))
        table.setHorizontalHeaderLabels(headers)
        table.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
        table.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)
        table.verticalHeader().hide()
        header = table.horizontalHeader()
        header.setSectionResizeMode(QHeaderView.ResizeMode.ResizeToContents)
        header.setSectionResizeMode(stretch_column, QHeaderView.ResizeMode.Stretch)
        return table

    def postgres_settings(self):
        dialog = QDialog(self)
        dialog.setWindowTitle("Подключение к PostgreSQL")
        form = QFormLayout(dialog)
        host = QLineEdit("localhost")
        port = QSpinBox()
        port.setRange(1, 65535)
        port.setValue(5432)
        database = QLineEdit()
        user = QLineEdit("postgres")
        password = QLineEdit()
        password.setEchoMode(QLineEdit.EchoMode.Password)
        if self.local_postgres:
            configured_port, configured_password = self.local_postgres
            host.setText("127.0.0.1")
            port.setValue(configured_port)
            database.setText("reading_planner")
            user.setText("planner")
            password.setText(configured_password)
            for field in (host, database, user):
                field.textEdited.connect(password.clear)
            port.valueChanged.connect(password.clear)
        form.addRow("Сервер", host)
        form.addRow("Порт", port)
        form.addRow("Имя базы данных", database)
        form.addRow("Пользователь", user)
        form.addRow("Пароль", password)

        buttons = QDialogButtonBox(
            QDialogButtonBox.StandardButton.Ok | QDialogButtonBox.StandardButton.Cancel
        )
        connect_button = buttons.button(QDialogButtonBox.StandardButton.Ok)
        connect_button.setText("Подключиться")
        buttons.button(QDialogButtonBox.StandardButton.Cancel).setText("Отмена")
        connect_button.setEnabled(False)

        def validate_fields():
            connect_button.setEnabled(all(field.text().strip() for field in (host, database, user)))

        for field in (host, database, user):
            field.textChanged.connect(validate_fields)
        validate_fields()
        buttons.accepted.connect(dialog.accept)
        buttons.rejected.connect(dialog.reject)
        form.addRow(buttons)
        database.setFocus()

        settings = None
        if dialog.exec() == QDialog.DialogCode.Accepted:
            settings = dict(
                host=host.text().strip(), port=port.value(), dbname=database.text().strip(),
                user=user.text().strip(), password=password.text(), connect_timeout=5,
            )
        dialog.deleteLater()
        return settings

    def switch_database(self, index):
        target = self.backend.itemText(index)
        previous_index = self.backend.findText(self.database.backend) if self.database else 0
        self.backend.setCurrentIndex(previous_index)
        if target == "SQLite" and self.database and self.database.backend == target:
            self.refresh_tables()
            return

        candidate = None
        errors = (sqlite3.Error,)
        try:
            if target == "SQLite":
                connection = sqlite3.connect(SQLITE_PATH)
                location = SQLITE_PATH.name
            else:
                try:
                    import psycopg
                except ImportError:
                    QMessageBox.warning(
                        self, "PostgreSQL", 'Установите драйвер: python -m pip install "psycopg[binary]"'
                    )
                    return
                errors += (psycopg.Error,)
                settings = self.postgres_settings()
                if settings is None:
                    return
                location = f"{settings['host']}:{settings['port']} / {settings['dbname']}"
                connection = psycopg.connect(**settings)
            candidate = ReadingDatabase(connection, target)
            candidate.initialize()
            rows = candidate.read_tables()
        except errors as error:
            if candidate is not None:
                candidate.close()
            self.database_error(f"Подключение к {target}", error)
            return

        if self.database is not None:
            self.database.close()
        self.database = candidate
        self.database_errors = errors
        self.backend.setCurrentIndex(index)
        self.statusBar().showMessage(f"{target} · {location}")
        self.save_button.setEnabled(True)
        self.refresh_button.setEnabled(True)
        self.show_tables(rows)

    def database_error(self, action, error):
        message = QMessageBox(QMessageBox.Icon.Warning, action, str(error).strip(), parent=self)
        message.setTextFormat(Qt.TextFormat.PlainText)
        message.exec()

    def show_tables(self, rows):
        for table, records in zip((self.books_table, self.plans_table), rows):
            table.setRowCount(len(records))
            for row, values in enumerate(records):
                for column, value in enumerate(values):
                    item = QTableWidgetItem()
                    item.setData(Qt.ItemDataRole.DisplayRole, value)
                    table.setItem(row, column, item)

    def refresh_tables(self):
        try:
            rows = self.database.read_tables()
        except self.database_errors as error:
            self.database_error("Не удалось обновить таблицы", error)
            return
        self.show_tables(rows)

    def reading_values(self):
        pages = self.read_positive_int(self.pages_input, "Осталось страниц")
        if pages is None:
            return None
        days = self.read_positive_int(self.deadline.lineEdit(), "Срок чтения (в днях)")
        if days is None:
            return None
        return pages, days

    def calculate(self):
        values = self.reading_values()
        if values is not None:
            self.result.setText(f"Дневная норма: {daily_pages(*values)} стр. в день.")

    def save_plan(self):
        values = self.reading_values()
        if values is None:
            return
        title = self.title_input.text().strip()
        if not title or "\x00" in title:
            QMessageBox.warning(self, "Ошибка ввода", "Введите название книги.")
            self.title_input.setFocus()
            return
        if max(values) > MAX_SQL_INTEGER:
            QMessageBox.warning(self, "Ошибка ввода", "Число страниц и срок должны быть не больше 2 147 483 647.")
            return
        try:
            rows = self.database.add_plan(title, *values)
        except self.database_errors as error:
            self.database_error("Не удалось сохранить план", error)
            return
        self.show_tables(rows)
        self.tabs.setCurrentWidget(self.plans_table)
        self.result.setText(f"План сохранён. Дневная норма: {daily_pages(*values)} стр. в день.")

    def read_positive_int(self, field, label):
        try:
            number = int(field.text().strip())
            if number <= 0:
                raise ValueError
        except ValueError:
            self.result.clear()
            QMessageBox.warning(
                self, "Ошибка ввода", f"В поле «{label}» введите целое число больше нуля."
            )
            field.setFocus()
            field.selectAll()
            return None
        return number

    def closeEvent(self, event):
        if self.database is not None:
            self.database.close()
        super().closeEvent(event)


if __name__ == "__main__":
    app = QApplication(sys.argv)
    window = ReadingPlanner()
    window.show()
    sys.exit(app.exec())
